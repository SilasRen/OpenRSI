_NEXT = {"crash": "constant", "constant": "linear", "linear": "gbm", "gbm": "gbm"}


class FakePolicy:
    """Scripted operator: drafts are random; Improve/Debug move one rung up the ladder."""

    def __init__(self, seed: int = 0):
        self.rng = random.Random(seed)
        self.updates = 0

    def generate(self, prompts, n, max_new_tokens=0, temperature=1.0, top_p=1.0):
        out = []
        for msgs in prompts:
            user = msgs[-1]["content"]
            row = []
            for _ in range(n):
                if "A previous solution" in user:
                    cur = next((k for k, v in _FAKE.items() if v.strip() in user), "crash")
                    kind = _NEXT[cur] if self.rng.random() < 0.8 else cur
                else:
                    kind = self.rng.choice(list(_FAKE))
                text = f"Plan: {kind}\n```python\n{_FAKE[kind]}```"
                row.append(Gen(text, [0], [1]))
            out.append(row)
        return out

    def update(self, gens, advantages, clip=1.0):
        self.updates += 1
        return {"loss": 0.0, "trained": sum(abs(a) > 1e-8 for a in advantages)}

    def save(self, path):
        import os
        os.makedirs(path, exist_ok=True)
        open(os.path.join(path, "FAKE"), "w").close()
