"""Policies for the offline experiment.

HFPolicy: a small Hugging Face causal LM (default Qwen2.5-Coder-1.5B-Instruct) that both
generates and is trained, in one process on one GPU. No SGLang, Ray, Megatron or SLIME.
Rollouts are generated by the current weights and used for exactly one optimizer step,
so the GSPO/GRPO importance ratio is 1 and the update reduces to the group-normalised
policy gradient  -sum_i A_i * mean_t log pi(y_i,t | x_i, y_i,<t).

FakePolicy: a scripted stand-in with no model, used by tests and --dry-run to check the
whole pipeline (tasks, executor, SOPO lookahead, evaluation, report) on a laptop.
"""
from __future__ import annotations

import random
from dataclasses import dataclass


@dataclass
class Gen:
    text: str
    prompt_ids: list[int]
    response_ids: list[int]


class HFPolicy:
    def __init__(self, model_path: str, device: str = "cuda", lr: float = 1e-6, max_len: int = 6144,
                 gen_batch: int = 16, grad_checkpointing: bool = True, train: bool = True):
        import torch
        from transformers import AutoModelForCausalLM, AutoTokenizer

        self.torch = torch
        self.device = device
        self.max_len = max_len
        self.gen_batch = gen_batch
        self.tok = AutoTokenizer.from_pretrained(model_path)
        self.tok.padding_side = "left"
        if self.tok.pad_token is None:
            self.tok.pad_token = self.tok.eos_token
        # fp32 master weights: bf16 weights silently drop updates at lr ~1e-6.
        dtype = torch.float32 if train else torch.bfloat16
        try:
            self.model = AutoModelForCausalLM.from_pretrained(model_path, dtype=dtype)
        except TypeError:  # transformers < 4.56
            self.model = AutoModelForCausalLM.from_pretrained(model_path, torch_dtype=dtype)
        self.model.to(device)
        self.model.config.use_cache = True
        if train:
            if grad_checkpointing:
                self.model.gradient_checkpointing_enable()
            self.opt = torch.optim.AdamW(self.model.parameters(), lr=lr, betas=(0.9, 0.99), weight_decay=0.0)

    def _template(self, messages):
        kwargs = dict(tokenize=False, add_generation_prompt=True)
        try:
            return self.tok.apply_chat_template(messages, enable_thinking=False, **kwargs)
        except TypeError:
            return self.tok.apply_chat_template(messages, **kwargs)

    def generate(self, prompts: list[list[dict]], n: int, max_new_tokens: int, temperature: float = 1.0,
                 top_p: float = 1.0) -> list[list[Gen]]:
        torch = self.torch
        self.model.eval()
        texts = [self._template(m) for m in prompts]
        out: list[list[Gen]] = [[] for _ in prompts]
        per_call = max(1, self.gen_batch // n)
        for s in range(0, len(texts), per_call):
            chunk = texts[s:s + per_call]
            enc = self.tok(chunk, return_tensors="pt", padding=True, truncation=True,
                           max_length=self.max_len - max_new_tokens).to(self.device)
            with torch.no_grad(), torch.autocast("cuda", dtype=torch.bfloat16, enabled=self.device.startswith("cuda")):
                seqs = self.model.generate(**enc, do_sample=True, temperature=temperature, top_p=top_p,
                                           max_new_tokens=max_new_tokens, num_return_sequences=n, use_cache=True,
                                           pad_token_id=self.tok.pad_token_id)
            plen = enc["input_ids"].shape[1]
            for k, seq in enumerate(seqs):
                i = s + k // n
                prompt_ids = [t for t, m in zip(enc["input_ids"][k // n].tolist(),
                                                enc["attention_mask"][k // n].tolist()) if m]
                resp = seq[plen:].tolist()
                while resp and resp[-1] == self.tok.pad_token_id:
                    resp.pop()
                out[i].append(Gen(self.tok.decode(resp, skip_special_tokens=True), prompt_ids, resp))
        return out

    def update(self, gens: list[Gen], advantages: list[float], clip: float = 1.0) -> dict:
        torch = self.torch
        items = [(g, a) for g, a in zip(gens, advantages) if abs(a) > 1e-8 and g.response_ids]
        if not items:
            return {"loss": 0.0, "trained": 0}
        self.model.train()
        self.opt.zero_grad(set_to_none=True)
        total = 0.0
        for g, a in items:
            ids = (g.prompt_ids + g.response_ids)[-self.max_len:]
            n_resp = min(len(g.response_ids), len(ids) - 1)
            x = torch.tensor([ids], device=self.device)
            with torch.autocast("cuda", dtype=torch.bfloat16, enabled=self.device.startswith("cuda")):
                logits = self.model(x).logits[:, :-1].float()
            logp = torch.log_softmax(logits, -1).gather(-1, x[:, 1:].unsqueeze(-1)).squeeze(-1)
            seq_logp = logp[:, -n_resp:].mean()
            loss = -(a * seq_logp) / len(items)
            loss.backward()
            total += float(loss.detach())
        gn = torch.nn.utils.clip_grad_norm_(self.model.parameters(), clip)
        self.opt.step()
        return {"loss": total, "trained": len(items), "grad_norm": float(gn)}

    def save(self, path: str):
        self.model.save_pretrained(path, safe_serialization=True)
        self.tok.save_pretrained(path)


